import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv('/Housing.csv')
df.head()
df = df[df['area']<8000]
df.head()

x = df['area']
y = df['price']
y.head()

plt.scatter(x,y)
plt.xlabel('area')
plt.ylabel('price')
plt.title('Housing Area vs Price')
plt.show()

x = x.to_numpy()
y = y.to_numpy()

#calculate Gradient Descent
def get_gradient(x,y,m,b):
    n=len(x)
    gradW=(2/n)*np.sum(x*(m*x+b-y))
    gradB=(2/n)*np.sum(m*x+b-y)
    return gradW,gradB

## Gradient Descent
def gradient_descent(x,y,m,b,e,iteration):

    for  i in range(iteration):
        gradW,gradB=get_gradient(x,y,m,b)
        m=m-e*(gradW)
        b=b-e*(gradB)
    return m,b

# normalizing data
x_mean = np.mean(x)
x_std = np.std(x)
y_mean = np.mean(y)
y_std = np.std(y)

x_scaled = (x - x_mean) / x_std
y_scaled = (y - y_mean) / y_std

# final slope
m=0
b=0
m,b=gradient_descent(x_scaled,y_scaled,m,b,0.001,1000)
y_pred = m*x_scaled + b
print(f"m={m},b={b}")

plt.scatter(x_scaled,y_scaled)
plt.plot(x_scaled,y_pred,'r-')
